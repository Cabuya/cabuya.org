#!/usr/bin/env node

/**
 * Generates `functions/lib/registry-ids.ts` from the registry tree.
 *
 * The badge endpoint needs to know which publisher ids exist, and it runs at
 * the edge where there is no filesystem to read `registry/` from. It cannot
 * import `src/lib/registry-loader.ts` either — that module is built on
 * `node:fs` by design, because it is the build-time door into a directory the
 * boundary rules keep at arm's length.
 *
 * So the list is inlined at build time, the same way the validator inlines its
 * schemas. Generated and committed, never hand-edited: a test asserts the
 * committed file still matches the tree, so a new entry that forgets this step
 * fails CI rather than silently 404ing its own badge.
 *
 * ## Why the endpoint needs the list at all
 *
 * Without it, `/badge/anything.svg` would render a plausible "not yet measured"
 * badge for an id nobody has ever reviewed — and "not yet measured" on a badge
 * that carries the protocol's name reads, to most people, as "in the registry,
 * pending". An unknown id has to 404.
 *
 * Usage: node scripts/generate-registry-ids.mjs [--check]
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const OUT = join(ROOT, 'functions/lib/registry-ids.ts');
const check = process.argv.includes('--check');

const dir = join(ROOT, 'registry/publishers');
const ids = readdirSync(dir)
  .filter((file) => file.endsWith('.json'))
  .map((file) => JSON.parse(readFileSync(join(dir, file), 'utf-8')))
  .map((entry) => entry.publisher_id)
  .sort();

const contents = `/**
 * Publisher ids that exist in the registry.
 *
 * GENERATED by \`scripts/generate-registry-ids.mjs\` — do not edit. Run
 * \`pnpm run registry:ids\` after adding or removing an entry;
 * \`registry:ids --check\` fails CI when this file has drifted from the tree.
 */

export const REGISTRY_IDS: ReadonlySet<string> = new Set([
${ids.map((id) => `  '${id}',`).join('\n')}
]);
`;

if (check) {
  const current = readFileSync(OUT, 'utf-8');
  if (current !== contents) {
    console.error(
      '❌ functions/lib/registry-ids.ts is stale — run `pnpm run registry:ids`'
    );
    process.exit(1);
  }
  console.log(`✅ registry ids current (${ids.length} entries)`);
  process.exit(0);
}

writeFileSync(OUT, contents);
console.log(`✅ wrote functions/lib/registry-ids.ts (${ids.length} entries)`);
